def cities_json():
    """The list for the page (``data-city-list``)."""
    return json.dumps(CITIES, ensure_ascii=False, separators=(",", ":"))


def city_in(text, governorate=""):
    """The city of the list named in ``text`` (e.g. the address read from an ID card), or "". The governorate's own
    cities are tried first; a name inside a longer one ("نصر" in "مدينة نصر") gives way to it, then the first one
    written wins: an address names the district before the governorate ("الدقي - الجيزة")."""
    text = _plain(text)
    if not text:
        return ""
    lists = [CITIES.get(governorate, [])] + [cities for code, cities in CITIES.items() if code != governorate]
    for cities in lists:
        found = [(text.index(_plain(city)), city) for city in cities if _plain(city) and _plain(city) in text]
        found = [(at, city) for at, city in found
                 if not any(city != other and _plain(city) in _plain(other) for _, other in found)]
        if found:
            return min(found, key=lambda item: item[0])[1]
    return ""


def _plain(text):
    """Arabic without the spelling differences of أ/إ/آ/ا, ة/ه and ى/ي (as typed or read from a card)."""
    table = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ة": "ه", "ى": "ي"})
    return " ".join((text or "").translate(table).split())
